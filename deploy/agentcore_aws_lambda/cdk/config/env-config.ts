import * as dotenv from 'dotenv';
import * as fs from 'fs';
import * as path from 'path';

/**
 * Environment configuration for TAC AgentCore deployment.
 * Reads from /deploy/agentcore_aws_lambda/.env and validates required variables.
 */

export interface TacEnvConfig {
  // AWS Configuration
  awsAccountId: string;
  awsRegion: string;
  // Twilio Configuration (non-secret)
  twilioPhoneNumber: string;
  twilioConversationConfigurationId: string;
  // AI IVR
  ivrSessionToken: string;
  /** JSON map of intent key -> {number, sendDigits}, for the Lambda /dial route. */
  ivrExtensionDestinations: string;
}

/**
 * Read the intent -> {number, sendDigits} map the Lambda /dial route serves.
 *
 * Generated by 'make build' from ivr-config.json via
 * IVRConfig.extension_destinations(), so Python owns the sendDigits rule.
 *
 * DO NOT "simplify" this by computing the map here instead. sendDigits encodes
 * the pre-dial pause as half-second 'w' characters, i.e. pauseSeconds * 2 of
 * them — and Python and JavaScript disagree on the rounding: Python's round()
 * is banker's rounding, so round(2.5) == 2, while Math.round(2.5) == 3. A
 * fractional extensionPauseSeconds would then make this Lambda send different
 * DTMF digits than the config model says it sends, and the caller would land
 * on the wrong extension. Reading the Python-generated file is what keeps one
 * implementation of that rule.
 */
function loadExtensionDestinations(configRoot: string): string {
  const generatedPath = path.resolve(
    configRoot,
    '../agent/ivr-extension-destinations.json'
  );
  if (!fs.existsSync(generatedPath)) {
    throw new Error(
      `Missing ${generatedPath}. Run 'make build' (or 'make deploy') to generate it.`
    );
  }

  let parsed: unknown;
  try {
    parsed = JSON.parse(fs.readFileSync(generatedPath, 'utf-8'));
  } catch (error) {
    throw new Error(
      `${generatedPath} is not valid JSON: ${(error as Error).message}\n` +
      `Re-run 'make build' to regenerate it.`
    );
  }

  // Fail at synth time rather than shipping a wrong-shaped value: the Lambda's
  // /dial route does a dict lookup on this, so an array or string would only
  // surface as a runtime error mid-call.
  if (typeof parsed !== 'object' || parsed === null || Array.isArray(parsed)) {
    throw new Error(
      `${generatedPath} must contain a JSON object mapping intent keys to ` +
      `{number, sendDigits}, but found ${Array.isArray(parsed) ? 'an array' : typeof parsed}.`
    );
  }

  // Re-serialize so the Lambda environment variable is compact and stable.
  return JSON.stringify(parsed);
}

/**
 * Loads and validates environment variables from .env file.
 *
 * @param configRoot - Path to cdk/ directory
 * @returns Validated environment configuration
 * @throws Error if required variables are missing
 */
export function loadEnvConfig(configRoot: string): TacEnvConfig {
  // Load environment variables from /deploy/agentcore_aws_lambda/.env (centralized)
  // configRoot is cdk/, so we go up 1 level to reach agentcore_aws_lambda/
  const envPath = path.resolve(configRoot, '../.env');
  dotenv.config({ path: envPath });

  // Validate required environment variables
  const requiredVars = [
    'AWS_ACCOUNT_ID',
    'AWS_REGION',
    'TWILIO_PHONE_NUMBER',
    'TWILIO_CONVERSATION_CONFIGURATION_ID',
    'IVR_SESSION_TOKEN',
  ];

  const missingVars = requiredVars.filter(varName => !process.env[varName]);
  if (missingVars.length > 0) {
    throw new Error(
      `Missing required environment variables in .env file:\n` +
      missingVars.map(v => `  - ${v}`).join('\n') +
      `\n\nPlease set these in: ${envPath}`
    );
  }

  // Return validated configuration
  return {
    awsAccountId: process.env.AWS_ACCOUNT_ID!,
    awsRegion: process.env.AWS_REGION!,
    twilioPhoneNumber: process.env.TWILIO_PHONE_NUMBER!,
    twilioConversationConfigurationId: process.env.TWILIO_CONVERSATION_CONFIGURATION_ID!,
    ivrSessionToken: process.env.IVR_SESSION_TOKEN!,
    ivrExtensionDestinations: loadExtensionDestinations(configRoot),
  };
}

