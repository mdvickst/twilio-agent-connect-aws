"""Create or update the IVR's Studio flow and point the phone number at it.

Idempotent: the flow is found by friendly name, so re-running after a config
change updates the existing flow rather than piling up duplicates.

Usage, from the repository root with the example's .env exported:

    PYTHONPATH=deploy/agentcore_aws_lambda uv run python -m studio.provision
"""

from __future__ import annotations

import os
import subprocess
import sys
from typing import Any
from urllib.parse import urlparse

from ivr_config import load_config
from twilio.base.exceptions import TwilioRestException
from twilio.rest import Client

from .flow_builder import build_flow_definition, flow_friendly_name
from .preflight import format_problems, run_check

COMMIT_MESSAGE = "Generated by tac_aws AI IVR (make deploy)"

LAMBDA_STACK_NAME = "TacLambdaStack"
LAMBDA_URL_OUTPUT_KEYS = ("VoiceWebhookUrl", "ConversationWebhookUrl")


def find_flow_by_name(client: Any, friendly_name: str) -> Any | None:
    """Return the flow with this friendly name, or None."""
    for flow in client.studio.v2.flows.list():
        if flow.friendly_name == friendly_name:
            return flow
    return None


def upsert_flow(client: Any, friendly_name: str, definition: dict[str, Any]) -> Any:
    """Create the flow, or update it in place if it already exists. Always published."""
    existing = find_flow_by_name(client, friendly_name)
    if existing is not None:
        return client.studio.v2.flows(existing.sid).update(
            friendly_name=friendly_name,
            status="published",
            definition=definition,
            commit_message=COMMIT_MESSAGE,
        )

    return client.studio.v2.flows.create(
        friendly_name=friendly_name,
        status="published",
        definition=definition,
        commit_message=COMMIT_MESSAGE,
    )


def attach_number(client: Any, phone_number_sid: str, webhook_url: str) -> None:
    """Point the number's voice webhook at the flow.

    ``voice_application_sid`` is cleared explicitly because Twilio resolves a
    TwiML App ahead of ``voice_url``.  A number that previously had a TwiML App
    would ignore the new webhook URL unless the app SID is removed first.
    """
    client.incoming_phone_numbers(phone_number_sid).update(
        voice_url=webhook_url,
        voice_method="POST",
        voice_application_sid="",
    )


def _parse_lambda_base_url(value: str) -> str | None:
    """Return the https base URL (scheme + netloc only) for *value*, or None if invalid."""
    parsed = urlparse(value)
    if parsed.scheme == "https" and parsed.netloc:
        return f"https://{parsed.netloc}"
    return None


def lambda_url_from_env() -> str:
    """Resolve the deployed Lambda Function URL base.

    Prefers IVR_LAMBDA_URL when set. Otherwise reads it from the CloudFormation
    stack output and strips any path, since the stack publishes full endpoint URLs
    rather than the base.

    Returns an absolute ``https://`` base URL with no trailing slash or path.
    Raises ``RuntimeError`` if no usable URL can be found from any source.
    """
    explicit = os.environ.get("IVR_LAMBDA_URL")
    if explicit:
        base = _parse_lambda_base_url(explicit)
        if base is None:
            raise RuntimeError(
                f"IVR_LAMBDA_URL {explicit!r} is not a valid https URL. "
                "Set it to the Lambda Function URL base, e.g. https://abc.lambda-url.region.on.aws"
            )
        return base

    for output_key in LAMBDA_URL_OUTPUT_KEYS:
        command = [
            "aws",
            "cloudformation",
            "describe-stacks",
            "--stack-name",
            LAMBDA_STACK_NAME,
            "--query",
            f"Stacks[0].Outputs[?OutputKey=='{output_key}'].OutputValue",
            "--output",
            "text",
        ]
        result = subprocess.run(command, capture_output=True, text=True, check=False)
        value = result.stdout.strip()
        if result.returncode == 0 and value and value != "None":
            # Outputs look like https://xxx.lambda-url.region.on.aws/twiml — strip the path.
            base = _parse_lambda_base_url(value)
            if base is not None:
                return base
        elif result.returncode != 0 and result.stderr.strip():
            print(f"  aws cloudformation ({output_key}): {result.stderr.strip()}", file=sys.stderr)

    raise RuntimeError(
        f"Could not resolve the Lambda Function URL from stack {LAMBDA_STACK_NAME}. "
        "Deploy the stacks first, or set IVR_LAMBDA_URL."
    )


def main() -> int:
    account_sid = os.environ.get("TWILIO_ACCOUNT_SID")
    api_key = os.environ.get("TWILIO_API_KEY")
    api_secret = os.environ.get("TWILIO_API_SECRET")
    session_token = os.environ.get("IVR_SESSION_TOKEN")

    if not (account_sid and api_key and api_secret):
        print("Set TWILIO_ACCOUNT_SID, TWILIO_API_KEY and TWILIO_API_SECRET.", file=sys.stderr)
        return 2
    if not session_token:
        print(
            "IVR_SESSION_TOKEN is not set. Run 'make configure' to generate one.",
            file=sys.stderr,
        )
        return 2

    config = load_config()
    client = Client(api_key, api_secret, account_sid)

    print("Checking Conversation Orchestrator capture rules...")
    try:
        problems = run_check(config)
    except Exception as error:
        print(f"  Could not read the configuration: {error}", file=sys.stderr)
        return 1

    if problems:
        print(format_problems(problems, config), file=sys.stderr)
        return 1
    print("  Capture rules OK.")

    lambda_url = lambda_url_from_env()
    print(f"Using Lambda URL: {lambda_url}")

    definition = build_flow_definition(config, lambda_url, session_token)
    friendly_name = flow_friendly_name(config)

    print("Validating the flow definition...")
    try:
        validation = client.studio.v2.flow_validate.update(
            friendly_name=friendly_name, status="published", definition=definition
        )
    except TwilioRestException as error:
        print(
            f"  Validation request failed: {error.status} {error.msg}\n"
            "  If the error names an unknown widget type, run "
            "'python -m studio.discover' to probe the real type string,\n"
            "  then update CR_WIDGET_TYPE in studio/widgets.py (UNVERIFIED constants).",
            file=sys.stderr,
        )
        return 1
    if not validation.valid:
        print(
            "  Studio rejected the definition.\n"
            "  Run 'python -m studio.discover' to probe the ConversationRelay widget "
            "type string,\n"
            "  then update CR_WIDGET_TYPE in studio/widgets.py (UNVERIFIED constants).",
            file=sys.stderr,
        )
        return 1
    print("  Valid.")

    print(f"Publishing flow {friendly_name!r}...")
    try:
        flow = upsert_flow(client, friendly_name, definition)
    except TwilioRestException as error:
        print(f"  Failed: {error.status} {error.msg}", file=sys.stderr)
        return 1
    print(f"  Flow SID: {flow.sid}")

    print(f"Pointing {config.twilio.phone_number} at the flow...")
    try:
        attach_number(client, config.twilio.phone_number_sid, flow.webhook_url)
    except TwilioRestException as error:
        print(
            f"  Failed: {error.status} {error.msg}\n"
            f"  The flow was published (SID {flow.sid}). "
            "Set the number's Voice webhook to the flow URL manually, or re-run this script.",
            file=sys.stderr,
        )
        return 1
    print("  Done.")

    print(
        f"\nIVR live on {config.twilio.phone_number}\n"
        f"  Console: https://console.twilio.com/us1/develop/studio/flows/{flow.sid}"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
